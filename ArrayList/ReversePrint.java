public class ReversePrint {
    public static void main(String[] args) {
        System.out.println("This is regarding revese * ");
        for (int i=5;i>=1;i--){
            System.out.print("");
            for(int j=1;j<=5;j++){
                System.out.print("*");
            }
            System.out.println();

        }
    }
}
